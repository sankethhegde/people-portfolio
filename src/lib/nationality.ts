const lookup = new Map<string, string>();
(() => {
  const names = typeof Intl.DisplayNames === 'function' ? new Intl.DisplayNames(['en'], { type: 'region' }) : null;
  for (const [code, words] of Object.entries(NATIONALITIES)) {
    for (const w of words) lookup.set(w.toLowerCase(), code);
    // Country names too: "India", "United Kingdom", "Türkiye"…
    const country = names?.of(code.toUpperCase());
    if (country) lookup.set(country.toLowerCase(), code);
  }
})();

/** ISO country code for a nationality or country name, or undefined if unknown. */
export function nationalityCode(nationality?: string): string | undefined {
  const key = nationality?.trim().toLowerCase();
  return key ? lookup.get(key) : undefined;
}

/** Nationalities offered in the editor (the first word for each country). */
export const NATIONALITY_SUGGESTIONS = Object.values(NATIONALITIES)
  .map((w) => w[0])
  .sort((a, b) => a.localeCompare(b));
